#!/usr/bin/env python3
"""HOST-ONLY evidence collector for the Q2-07 host slice.

Assembles repo/evidence/host_slice.json from:
  * the per-step manifest written by scripts/build_host.sh (command, exit code, ms)
  * evidence/host/host_bench.csv            (bench rows, all scope=HOST-ONLY)
  * evidence/host/differential.json         (protobufjs 7.6.5 differential report)
  * evidence/host/materializer_check.json   (tape -> object materializer check)
  * sha256 / size of every artifact that a reader would want to verify

The output states scope=HOST-ONLY and an explicit not_claimed list. No device was
involved in any of these numbers.
"""
from __future__ import annotations

import argparse
import csv
import glob
import hashlib
import json
import os
import platform
import subprocess
import sys


def sha256_file(path: str) -> dict:
    h = hashlib.sha256()
    size = 0
    with open(path, "rb") as f:
        while True:
            b = f.read(1 << 20)
            if not b:
                break
            h.update(b)
            size += len(b)
    return {"bytes": size, "sha256": h.hexdigest()}


def rel(repo: str, path: str) -> str:
    try:
        return os.path.relpath(path, repo).replace("\\", "/")
    except ValueError:
        return path


def read_steps(path: str) -> list:
    steps = []
    if not path or not os.path.exists(path):
        return steps
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) != 4:
                continue
            name, cmd, rc, ms = parts
            steps.append(
                {
                    "step": name,
                    "command": cmd,
                    "exit_code": int(rc),
                    "duration_ms": int(ms),
                }
            )
    return steps


def read_bench(path: str) -> dict:
    out = {}
    if not path or not os.path.exists(path):
        return out
    with open(path, "r", encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            ds = row["dataset"]
            entry = out.setdefault(
                ds,
                {
                    "scope": row["scope"],
                    "card_file": row["card_file"],
                    "card_bytes": int(row["card_bytes"]),
                    "card_sha256": row["card_sha256"],
                    "payload_bytes": int(row["payload_bytes"]),
                    "frames": int(row["frames"]),
                    "messages": int(row["messages"]),
                    "fields": int(row["fields"]),
                    "reps": int(row["reps"]),
                    "compiler": row["compiler"],
                    "host_os": row["host_os"],
                    "metrics": {},
                },
            )
            entry["metrics"][row["metric"]] = {
                "value": row["value"],
                "unit": row["unit"],
            }
    return out


def read_json(path: str):
    if not path or not os.path.exists(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as e:  # noqa: BLE001
        return {"_error": f"{type(e).__name__}: {e}"}


def git_info(repo: str) -> dict:
    def run(*args):
        try:
            return (
                subprocess.run(
                    ["git", "-C", repo, *args],
                    capture_output=True,
                    text=True,
                    timeout=20,
                    check=False,
                )
                .stdout.strip()
            )
        except Exception:  # noqa: BLE001
            return ""

    rev = run("rev-parse", "HEAD")
    branch = run("rev-parse", "--abbrev-ref", "HEAD")
    dirty = run("status", "--porcelain")
    lines = [l for l in dirty.splitlines() if l.strip()]
    # Evidence outputs are regenerated by this run; they are not source dirt.
    source_dirty = [
        l for l in lines
        if not l[3:].startswith(("evidence/host/", "evidence/host_slice.json"))
    ]
    return {
        "branch": branch,
        "head": rev,
        "dirty_files": len(source_dirty),
        "dirty_files_raw": len(lines),
        "note": "source dirty files only; evidence outputs excluded (see dirty_files_raw)",
    }


def env_info() -> dict:
    info = {
        "host_os": platform.platform(),
        "machine": platform.machine(),
        "cpu_count": os.cpu_count(),
        "python": platform.python_version(),
    }
    for cmd in (["node", "--version"], ["npm", "--version"]):
        try:
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=20, check=False)
            if r.returncode == 0:
                info[cmd[0]] = r.stdout.strip()
        except Exception:  # noqa: BLE001
            pass
    return info


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--steps", default="")
    ap.add_argument("--bench-csv", default="")
    ap.add_argument("--diff-report", default="")
    ap.add_argument("--materializer-report", default="")
    ap.add_argument("--diff-mode", default="none")
    ap.add_argument("--compiler-kind", default="unknown")
    ap.add_argument("--compiler-name", default="unknown")
    ap.add_argument("--compiler-version", default="unknown")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    repo = os.path.abspath(args.repo)
    steps = read_steps(args.steps)
    bench = read_bench(args.bench_csv)
    diff = read_json(args.diff_report)
    mat = read_json(args.materializer_report)

    # ---- artifacts -------------------------------------------------------
    patterns = [
        "build/host/host_tests.exe",
        "build/host/host_decode_dump.exe",
        "build/host/host_bench.exe",
        "evidence/host/host_bench.csv",
        "evidence/host/differential.json",
        "evidence/host/materializer_check.json",
        "evidence/host/corpus/corpus.json",
        "evidence/host/corpus_cpp/meta.json",
        "bench/data/s1_user_1kb.bin",
        "bench/data/s3_100mb.bin",
        "build/host/s1dump/s1_frame0.tape.bin",
        "build/host/s1dump/s1_frame0.norm.json",
        "scripts/build_host.sh",
        "bench/gen_cards.py",
        "src/host/materializer/materializer.ts",
        "src/host/tape/tape.h",
        "src/host/tape/tape.cpp",
        "src/host/decoder/wire_reader.h",
        "src/host/decoder/wire_reader.cpp",
        "src/host/decoder/decode_user.cpp",
        "src/host/decoder/conformance.cpp",
        "src/host/decoder/norm.cpp",
        "src/host/decoder/object_model.h",
        "src/host/decoder/object_model.cpp",
        "src/host/decoder/map_order.h",
        "src/host/decoder/map_order.cpp",
        "src/host/decoder/generated/q207_demo_fields.h",
        "src/host/tests/test_wire.cpp",
        "src/host/tests/test_vectors.cpp",
        "src/host/tests/test_tape.cpp",
        "src/host/tests/test_decode.cpp",
        "src/host/tests/test_object_model.cpp",
        "src/host/tests/wire_vectors_data.inc",
        "src/host/tests/test_framework.h",
        "src/host/tests/main.cpp",
        "src/host/tests/README.md",
        "src/host/ts/gen_corpus.mjs",
        "src/host/ts/differential.mjs",
        "src/host/ts/materializer_check.mjs",
        "proto/example.proto",
        "scripts/gen_fields.py",
        "scripts/check_batch_sample.py",
        "app/entry/src/main/cpp/decode_napi.h",
        "app/entry/src/main/cpp/decode_napi.cpp",
        "app/entry/src/main/ets/types/libentry/index.d.ts",
        "app/entry/src/ohosTest/ets/test/EntryNapi.test.ets",
        "evidence/host/batch/user_batch_c20_plus_empty.wire",
        "evidence/host/batch/user_batch_c20_plus_empty.json",
        "build/host/logs/tests.log",
    ]
    artifacts = {}
    missing = []
    for pat in patterns:
        matches = [p for p in sorted(glob.glob(os.path.join(repo, pat))) if os.path.isfile(p)]
        if not matches:
            missing.append(pat)
        for path in matches:
            artifacts[rel(repo, path)] = sha256_file(path)
    if missing:
        print("evidence missing required artifacts:", ", ".join(missing), file=sys.stderr)
        return 1

    # ---- test counts from the test log if present ------------------------
    test_summary = {}
    tests_log = os.path.join(repo, "build/host/logs/tests.log")
    if os.path.exists(tests_log):
        with open(tests_log, "r", encoding="utf-8", errors="replace") as f:
            text = f.read()
        for line in text.splitlines():
            if "TESTS PASSED:" in line:
                nums = [int(x) for x in line.replace(",", "").split() if x.isdigit()]
                if len(nums) >= 2:
                    test_summary.update({"passed": nums[0], "failed": nums[1]})
            if "38-vector golden:" in line:
                test_summary["golden_vectors"] = line.strip()

    steps_ok = all(s["exit_code"] == 0 for s in steps) if steps else False
    diff_ok = bool(diff and diff.get("ok"))
    mat_ok = bool(mat and mat.get("ok"))
    mat_users = (mat or {}).get("users", "?")
    diff_cases = (diff or {}).get("cases_in_corpus", "?")

    evidence = {
        "scope": "HOST-ONLY",
        "slice": "Q2-07 host vertical slice v0 (wire reader + tape + materializer + differential + bench)",
        "device_measured": False,
        "not_claimed": ["device performance", "1.5x", "700ms"],
        "explicitly_not_measured": [
            "OpenHarmony / ArkTS runtime behaviour",
            "NAPI bridge cost (c_call) and per-object construction cost (c_con)",
            "device CPU / thermal / memory behaviour",
            "any 1.5x speed-up or 700 ms end-to-end claim",
        ],
        "what_it_proves": [
            "the wire reader's decision order (tag -> wire -> len<=remaining -> len<=cap -> alloc) is executable and judged by 38 W0 golden vectors",
            "negative int32 (10-byte varint), non-shortest varint, packed/unpacked, map, oneof, proto3 optional decode correctly into POD",
            "the row tape v0 layout round-trips, is byte-reproducible and has a verifier that rejects tampered buffers",
            f"tape -> plain-object materialization reproduces the C++ object graph exactly ({mat_users} users, sha256 equality)",
            f"object graph and re-encoded bytes agree with protobufjs 7.6.5 on a {diff_cases}-case corpus (no undocumented difference)",
        ],
        "toolchain": {
            "kind": args.compiler_kind,
            "compiler": args.compiler_name,
            "compiler_version": args.compiler_version,
            "note": (
                "native HOST compiler; NOT the OpenHarmony NDK cross-toolchain. "
                "Device-side C++/ASan builds remain BLOCKED (no board)."
            ),
        },
        "environment": env_info(),
        "git": git_info(repo),
        "steps": steps,
        "steps_all_zero": steps_ok,
        "tests": test_summary,
        "differential_mode": args.diff_mode,
        "differential": diff,
        "materializer": mat,
        "bench": bench,
        "artifacts": artifacts,
        "commands": [
            "bash repo/scripts/build_host.sh",
            "python repo/bench/gen_cards.py --out repo/bench/data",
            "repo/build/host/host_tests.exe",
            "repo/build/host/host_bench.exe --card bench/data/s1_user_1kb.bin --dataset s1_user_1kb --reps 5",
            "repo/build/host/host_bench.exe --card bench/data/s3_100mb.bin --dataset s3_100mb --reps 5",
            "node repo/src/host/ts/gen_corpus.mjs repo/evidence/host/corpus",
            "repo/build/host/host_decode_dump.exe --corpus repo/evidence/host/corpus --out repo/evidence/host/corpus_cpp --meta repo/evidence/host/corpus_cpp/meta.json",
            "node repo/src/host/ts/differential.mjs --corpus repo/evidence/host/corpus --cpp repo/evidence/host/corpus_cpp --out repo/evidence/host/differential.json",
            "node repo/src/host/ts/materializer_check.mjs --tape build/host/s1dump/s1_frame0.tape.bin --norm build/host/s1dump/s1_frame0.norm.json --out repo/evidence/host/materializer_check.json",
        ],
        "results": {
            "build_and_tests_ok": steps_ok and bool(test_summary) and test_summary.get("failed", 1) == 0,
            "golden_vectors_ok": "38/38" in test_summary.get("golden_vectors", ""),
            "differential_ok": diff_ok,
            "materializer_ok": mat_ok,
            "bench_csv": rel(repo, os.path.abspath(args.bench_csv)) if args.bench_csv else "",
        },
        "limitations": [
            "no ASan/UBSan run in this slice: the allocation-order property is asserted with an instrumented counter and an overridden global operator new, not with a sanitizer",
            "the 100 MB S3-like card is a synthetic data card, not a real application trace",
            "map iteration order, unknown-field retention and protobufjs 8.x semantics are out of scope for v0",
            "oneof is decoded keep-all (protobufjs 7.6.5 behaviour); the spec/last-wins arm only records the discriminator",
        ],
    }

    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(evidence, f, indent=2, ensure_ascii=False)
        f.write("\n")

    ok = (
        steps_ok
        and bool(test_summary)
        and test_summary.get("failed", 1) == 0
        and diff_ok
        and mat_ok
    )
    print(f"evidence: {rel(repo, args.out)}")
    print(f"  steps_all_zero={steps_ok} tests={test_summary} differential_ok={diff_ok} materializer_ok={mat_ok}")
    print(f"  artifacts hashed: {len(artifacts)}")
    if not ok:
        print("evidence records a FAILING step; see 'steps' in the JSON", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
